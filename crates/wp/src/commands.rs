pub fn by_key(key: &str) -> Option<Cmd> {
    COMMANDS.iter().find(|c| c.key == key).map(|c| c.id)
}

pub fn info(id: Cmd) -> &'static Command {
    COMMANDS.iter().find(|c| c.id == id).expect("every Cmd is registered")
}
