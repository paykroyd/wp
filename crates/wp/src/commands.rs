pub struct Command {
    pub id: Cmd,
    /// Stable id used in config bindings.
    pub key: &'static str,
    pub title: &'static str,
    pub category: &'static str,
    /// Extra words the palette should match.
    pub aliases: &'static str,
    /// Listed in the palette (plain cursor keys are not).
    pub listed: bool,
}

macro_rules! cmd {
    ($id:ident, $key:literal, $title:literal, $cat:literal) => {
        Command { id: Cmd::$id, key: $key, title: $title, category: $cat, aliases: "", listed: true }
    };
    ($id:ident, $key:literal, $title:literal, $cat:literal, $aliases:literal) => {
        Command { id: Cmd::$id, key: $key, title: $title, category: $cat, aliases: $aliases, listed: true }
    };
    (hidden $id:ident, $key:literal, $title:literal, $cat:literal) => {
        Command { id: Cmd::$id, key: $key, title: $title, category: $cat, aliases: "", listed: false }
    };
}

